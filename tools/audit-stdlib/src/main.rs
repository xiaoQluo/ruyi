// stdlib audit tool for Ruyi.
//
// Scans the standard library (stdlib/*.ry) for 8 documented modules
// (array, collections, map, set, string, math, time, json) and emits
// a Markdown report at docs/stdlib-audit-v0.5.5.md. The report lists
// every exported function / class / trait / constant in each module,
// flags bodies that look like stubs (contain only a TODO comment or
// an unimplemented!() marker), and explicitly notes modules whose
// source file does not yet exist.
//
// No dependencies: pure stdlib + std::fs / std::path reading.
//
// @author 罗泽罡
// @date 2026-07-10

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// One documented audit entry — corresponds to a row in the report.
#[derive(Debug)]
struct Module {
    /// Display name used in headings (e.g. `array`, `math`).
    name: &'static str,
    /// Module status: implemented (file present) or unimpl (file missing).
    status: Status,
    /// On-disk path of the source file the audit drew signatures from.
    /// `None` when the module file does not exist (math / time / json).
    source: Option<PathBuf>,
    /// Optional narrowing: when `source` covers multiple modules, this
    /// filters exported items by leading keyword (`ArrayIterator`,
    /// `Map`, `Set`, …). `None` means the whole file belongs to the
    /// module.
    filter: Option<&'static [&'static str]>,
}

#[derive(Debug, Clone, Copy)]
enum Status {
    Implemented,
    NotImplemented,
}

/// One exported item extracted from a `.ry` source file.
#[derive(Debug)]
struct Item {
    kind: &'static str, // `fn`, `class`, `trait`, `const`
    name: String,        // e.g. `ArrayIterator.new`
    signature: String,   // the source line, trimmed
    is_stub: bool,       // body is a TODO or unimplemented!() marker
}

fn main() {
    // Workspace root: tools/audit-stdlib/ → ../../
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let workspace_root = manifest_dir
        .parent()
        .and_then(Path::parent)
        .expect("workspace root resolves to tools/audit-stdlib/../..");
    let stdlib_dir = workspace_root.join("stdlib");
    let docs_dir = workspace_root.join("docs");
    let report_path = docs_dir.join("stdlib-audit-v0.5.5.md");

    let modules = [
        Module {
            name: "array",
            status: Status::Implemented,
            source: Some(stdlib_dir.join("collections.ry")),
            filter: Some(&["ArrayIterator", "ArrayOps"]),
        },
        Module {
            name: "collections",
            status: Status::Implemented,
            source: Some(stdlib_dir.join("collections.ry")),
            filter: Some(&["Iterator"]),
        },
        Module {
            name: "map",
            status: Status::Implemented,
            source: Some(stdlib_dir.join("collections.ry")),
            filter: Some(&["Map", "MapIterator"]),
        },
        Module {
            name: "set",
            status: Status::Implemented,
            source: Some(stdlib_dir.join("collections.ry")),
            filter: Some(&["Set", "SetIterator"]),
        },
        Module {
            name: "string",
            status: Status::Implemented,
            source: Some(stdlib_dir.join("string.ry")),
            filter: None,
        },
        Module {
            name: "math",
            status: Status::NotImplemented,
            source: None,
            filter: None,
        },
        Module {
            name: "time",
            status: Status::NotImplemented,
            source: None,
            filter: None,
        },
        Module {
            name: "json",
            status: Status::NotImplemented,
            source: None,
            filter: None,
        },
    ];

    let mut report = String::new();
    write_report_header(&mut report);
    for module in &modules {
        audit_module(&mut report, module);
    }
    write_report_footer(&mut report);

    fs::create_dir_all(&docs_dir).expect("create docs/");
    fs::write(&report_path, &report).expect("write report");
    println!("Wrote {}", report_path.display());
}

